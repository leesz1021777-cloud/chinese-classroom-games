export function expansionPack() {
  const units: Unit[] = [],
    lessons: Lesson[] = [],
    questions: Question[] = []
  const stamp = '2026-10-12T00:00:00.000Z'
  themes.forEach((theme, themeIndex) => {
    const unitId = `extra-${theme.bookId}-${theme.id}`
    units.push({ id: unitId, bookId: theme.bookId, name: theme.name, order: 10 + themeIndex })
    theme.topics.forEach((topic, topicIndex) => {
      const lessonId = `${unitId}-${topicIndex}`
      lessons.push({
        id: lessonId,
        unitId,
        name: topic.name,
        order: topicIndex,
        confirmed: false,
        topic: false,
      })
      const add = (
        key: string,
        data: Partial<Question> &
          Pick<Question, 'type' | 'prompt' | 'options' | 'answers' | 'explanation'>,
      ) =>
        questions.push({
          id: `pack2-${lessonId}-${key}`,
          versionId: 'pep-2024',
          bookId: theme.bookId,
          unitId,
          lessonId,
          knowledge: topic.name,
          difficulty: 'easy',
          games: gameMap[data.type],
          notes: '原创拓展练习，非已核实教材课目。请教师按教学进度确认。',
          enabled: true,
          createdAt: stamp,
          updatedAt: stamp,
          ...data,
        })
      const pool = [...new Set([...topic.characters.map(([char]) => char), ...topic.contrast])]
      topic.characters.forEach(([answer, clue], i) =>
        add(`char-${i}`, {
          type: 'choice',
          prompt: clue,
          options: pool,
          answers: [answer],
          explanation: `正确汉字是“${answer}”。${clue.includes('由') ? clue.replace('是哪一个？', '。') : '请结合词语认读，再观察字形。'}`,
        }),
      )
      topic.words.forEach(([prompt, options, answers, explanation], i) =>
        add(`word-${i}`, {
          type: 'word',
          prompt,
          options,
          answers,
          explanation,
          difficulty: i === 2 ? 'challenge' : i === 1 ? 'normal' : 'easy',
        }),
      )
      topic.sentences.forEach((tokens, i) => {
        const order = tokens.map((_, n) => n),
          orders = tokens[0] === '今天' ? [order, [1, 0, ...order.slice(2)]] : [order]
        add(`sentence-${i}`, {
          type: 'sentence',
          prompt: `${topic.name}：把词语排成通顺的句子。`,
          options: [],
          answers: [],
          tokens,
          orders,
          explanation: orders.map((o) => o.map((n) => tokens[n]).join('')).join(' / '),
          difficulty: i === 1 ? 'challenge' : 'normal',
        })
      })
      add('reading', {
        type: 'reading',
        prompt: `${topic.name}：跟着光点读一读。`,
        options: [],
        answers: [],
        readingText: topic.reading,
        explanation: '教师领读，遇到标点停一停，再请大家接龙读。',
      })
      const [prompt, options, answer, parts, tone] = topic.phonics
      add('pinyin', {
        type: 'pinyin',
        prompt,
        options,
        answers: [answer],
        syllable: answer,
        parts,
        explanation: `正确音节是 ${answer}。卡片顺序由教师明确配置，不靠拼接猜读音。`,
        difficulty: 'normal',
      })
      add('tone', {
        type: 'tone',
        prompt: `${answer} 是第几声？`,
        options: ['1', '2', '3', '4'],
        answers: [String(tone)],
        tone,
        explanation: `${answer} 是第${tone}声。请跟老师读一读。`,
      })
    })
  })
  const phonics = phonicsPack()
  return {
    units: [...units, phonics.unit],
    lessons: [...lessons, ...phonics.lessons],
    questions: [...questions, ...phonics.questions],
  }
}
export function upgradeContent(current: Database): { db: Database; added: number } {
  if ((current.contentRevision ?? 1) >= CONTENT_REVISION) return { db: current, added: 0 }
  const db = structuredClone(current),
    pack = expansionPack()
  for (const unit of pack.units)
    if (
      db.books.some((b) => b.id === unit.bookId && b.versionId === 'pep-2024') &&
      !db.units.some((u) => u.id === unit.id)
    )
      db.units.push(unit)
  for (const lesson of pack.lessons) {
    const expected = pack.units.find((u) => u.id === lesson.unitId)!
    if (
      db.units.some((u) => u.id === expected.id && u.bookId === expected.bookId) &&
      !db.lessons.some((l) => l.id === lesson.id)
    )
      db.lessons.push(lesson)
  }
  let added = 0
  for (const question of pack.questions)
    if (
      db.lessons.some((l) => l.id === question.lessonId && l.unitId === question.unitId) &&
      db.units.some((u) => u.id === question.unitId && u.bookId === question.bookId) &&
      db.books.some((b) => b.id === question.bookId && b.versionId === question.versionId) &&
      !db.questions.some((q) => q.id === question.id)
    ) {
      db.questions.push(question)
      added++
    }
  db.contentRevision = CONTENT_REVISION
  return { db: databaseSchema.parse(db), added }
}
